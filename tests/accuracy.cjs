function run(title, sets) {
    let ok = 0;
    let total = 0;
    const fails = [];
    for (const [name, cases] of Object.entries(sets)) {
        const kb = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'kb', `${name}.json`), 'utf8'));
        const bot = new Assistant(kb);
        for (const [question, expected] of cases) {
            const r = bot.answer(question);
            const got = r.type === 'answer' ? r.id : null;
            total++;
            if (got === expected) ok++;
            else fails.push(`${name}: «${question}» → ${got} (${r.score.toFixed(2)}), ждали ${expected}`);
        }
    }
    console.log(`${title}: ${ok}/${total} (${Math.round((ok / total) * 100)}%)`);
    fails.forEach((f) => console.log('  ✗', f));
    return ok / total;
}

const tuned = run('основной набор', CASES);
const held = run('отложенный набор', HELD_OUT);
// Поиск без нейросети не отличает «обувь 38 размера» от статьи про размеры — такие промахи ожидаемы
assert.ok(tuned >= 0.9 && held >= 0.75, 'точность упала ниже допустимой');
